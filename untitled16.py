import pandas as pd
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
from networkx.algorithms import community

# ==========================================
# STEP 1: GENERATE CONTINUOUS RAW PRODUCTION DATA
# ==========================================
np.random.seed(42)
num_rows = 30
recipes = ['R_Alpha', 'R_Beta', 'R_Gamma', 'R_Delta', 'R_Isolated']
machines = ['Machine_1', 'Machine_2']

# Simulate an active factory timeline over a few days
time_range = pd.date_range(start='2026-09-20 00:00:00', periods=num_rows, freq='3h')

df_raw = pd.DataFrame({
    'Datetime': np.random.choice(time_range, size=num_rows, replace=False), # Out of order
    'machine_id': np.random.choice(machines, size=num_rows),
    'recipe_id': np.random.choice(recipes, size=num_rows),
    'lot_id': [f'LOT_{100+i}' for i in range(num_rows)],
    'lot_qty': np.random.randint(50, 500, size=num_rows)
})

# Ensure Datetime format
df_raw['Datetime'] = pd.to_datetime(df_raw['Datetime'])


# ==========================================
# STEP 2: SHIFT AND FILTER BY DOWNTIME GAP
# ==========================================
# Define maximum time allowed to count as a back-to-back transition
MAX_GAP = pd.Timedelta(hours=12)

# Sort chronologically to track true physical sequence
df_sorted = df_raw.sort_values(by='Datetime').copy()

# Group by machine to keep transition threads isolated
df_group = df_sorted.groupby('machine_id')

# Shift subsequent recipe and its execution timestamp
df_sorted['next_recipe_id'] = df_group['recipe_id'].shift(-1)
df_sorted['next_datetime'] = df_group['Datetime'].shift(-1)

# Calculate elapsed time between lots
df_sorted['time_elapsed'] = df_sorted['next_datetime'] - df_sorted['Datetime']

# Keep rows where a next recipe exists AND the transition gap is close enough
valid_transition_mask = (
    df_sorted['next_recipe_id'].notna() &
    (df_sorted['time_elapsed'] <= MAX_GAP)
)
df_transitions = df_sorted[valid_transition_mask].copy()


# ==========================================
# STEP 3: COMPUTE THE TRANSITION PROBABILITY MATRIX
# ==========================================
# Cross-tabulate occurrences of every transition pair
counts = pd.crosstab(df_transitions['recipe_id'], df_transitions['next_recipe_id'])

# Guarantee a completely square matrix across all active recipe IDs
all_unique_recipes = sorted(list(df_raw['recipe_id'].unique()))
counts = counts.reindex(index=all_unique_recipes, columns=all_unique_recipes, fill_value=0)

# Normalize row-wise to find probabilities (Sum of row = 1.0)
transition_matrix = counts.div(counts.sum(axis=1).clip(lower=1), axis=0)

print("--- Transition Probability Matrix ---")
print(transition_matrix.round(2))
print("\n" + "="*50 + "\n")


# ==========================================
# STEP 4: GENERATE THE NETWORKX DIRECTED GRAPH
# ==========================================
G = nx.DiGraph()

# Feed matrix relationships into network edges
for from_recipe in transition_matrix.index:
    for to_recipe in transition_matrix.columns:
        prob = transition_matrix.loc[from_recipe, to_recipe]
        if prob > 0:
            G.add_edge(from_recipe, to_recipe, weight=prob)


# ==========================================
# STEP 5: RUN NETWORK ANALYTICS SUBGROUP DETECTION
# ==========================================
print("--- SUBGROUP & COMMUNITY DETECTION ---")

# 1. Catch strictly closed subgroups (Attracting Components)
closed_subgroups = list(nx.attracting_components(G))
for i, group in enumerate(closed_subgroups, 1):
    print(f"Hard Boundary Subgroup {i} (Closed Class): {list(group)}")

# 2. Catch individual recipes trapped inside self-loops
for node in G.nodes():
    successors = list(G.successors(node))
    if successors == [node]:
        print(f"Self-Isolated Node: '{node}' loops into itself and never exits.")

# 3. Soft Communities via Louvain Modularity Clustering
soft_communities = community.louvain_communities(G, weight='weight', seed=42)
for i, comm in enumerate(soft_communities, 1):
    print(f"Soft Connected Community {i}: {list(comm)}")


# ==========================================
# STEP 6: VISUALIZE RELATIONSHIPS
# ==========================================
plt.figure(figsize=(10, 7))

# Calculate spatial layout positioning (spring layout spaces clusters nicely)
pos = nx.spring_layout(G, k=1.2, seed=42)

# Dynamic coloring map based on Louvain community assignment
community_map = {}
for i, comm in enumerate(soft_communities):
    for node in comm:
        community_map[node] = i
colors = [community_map[node] for node in G.nodes()]

# Draw the infrastructure nodes
nx.draw_networkx_nodes(G, pos, node_size=1200, node_color=colors, cmap=plt.cm.Set3, edgecolors='black')

# Separate self-loops from directional arrows to keep the visual neat
standard_edges = [(u, v) for u, v in G.edges() if u != v]
self_loops = [(u, v) for u, v in G.edges() if u == v]

# Draw standard directed lines between recipes
nx.draw_networkx_edges(G, pos, edgelist=standard_edges, arrowstyle='->', arrowsize=20,
                       edge_color='gray', width=1.5, connectionstyle='arc3,rad=0.15')

# Draw circular arrows for self-transitions
nx.draw_networkx_edges(G, pos, edgelist=self_loops, arrowstyle='->', arrowsize=15,
                       edge_color='darkred', width=1.0, connectionstyle='arc3,rad=0.4')

# Label nodes with recipe names
nx.draw_networkx_labels(G, pos, font_size=10, font_weight='bold')

# Pull weight metrics to label lines with their transition probability percentages
edge_labels = {(u, v): f"{G[u][v]['weight']:.2f}" for u, v in standard_edges}
nx.draw_networkx_edge_labels(G, pos, edge_labels=edge_labels, font_size=8, label_pos=0.3)

plt.title("Recipe Transition Probability Network Map\n(Colors indicate Soft Communities | Red loops indicate self-transitions)", fontsize=12, fontweight='bold')
plt.axis('off')
plt.tight_layout()
plt.show()

