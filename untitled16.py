import networkx as nx
import matplotlib.pyplot as plt
from networkx.algorithms import community

# ==========================================
# STEP 1: GENERATE LARGE SCALED PRODUCTION DATA
# ==========================================
np.random.seed(42)

# 20 Recipes, 10 Machines, ~110 rows per machine
recipes = [f'R_{i:02d}' for i in range(1, 21)]
machines = [f'Machine_{i:02d}' for i in range(1, 11)]

df_list = []
start_time = pd.Timestamp('2026-09-01 00:00:00')

# Simulate continuous timelines per machine
for m in machines:
    # Generate 110 records per machine
    m_times = sorted([start_time + pd.Timedelta(hours=int(x)) for x in np.random.choice(range(500), size=110, replace=False)])

    # Assign recipes with structural affinities to create realistic clusters
    if m in machines[0:4]:     # Machines 1-4 specialize in R_01 to R_08
        m_recipes = np.random.choice(recipes[0:8], size=110)
    elif m in machines[4:8]:   # Machines 5-8 specialize in R_09 to R_16
        m_recipes = np.random.choice(recipes[8:16], size=110)
    else:                      # Machines 9-10 specialize in R_17 to R_20
        m_recipes = np.random.choice(recipes[16:20], size=110)

    df_m = pd.DataFrame({
        'Datetime': m_times,
        'machine_id': m,
        'recipe_id': m_recipes,
        'lot_id': [f'LOT_{np.random.randint(100000, 999999)}' for _ in range(110)],
        'lot_qty': np.random.randint(50, 500, size=110)
    })
    df_list.append(df_m)

# Combine into one master dataframe and shuffle order to simulate raw logs
df_raw = pd.concat(df_list).sample(frac=1).reset_index(drop=True)


# ==========================================
# STEP 2: SHIFT WITHIN GROUPS TO ENSURE LOGICAL CONTINUITY
# ==========================================
MAX_GAP = pd.Timedelta(hours=12)

# Sort chronologically to align handoffs
df_sorted = df_raw.sort_values(by='Datetime').copy()

# Group by machine id ONLY for the sequence tracking step
df_group = df_sorted.groupby('machine_id')
df_sorted['next_recipe_id'] = df_group['recipe_id'].shift(-1)
df_sorted['next_datetime'] = df_group['Datetime'].shift(-1)
df_sorted['time_elapsed'] = df_sorted['next_datetime'] - df_sorted['Datetime']

# Sever links that represent long machine downtime gaps
valid_transition_mask = (
    df_sorted['next_recipe_id'].notna() &
    (df_sorted['time_elapsed'] <= MAX_GAP)
)
df_transitions = df_sorted[valid_transition_mask].copy()


# ==========================================
# STEP 3: COMPUTE MACHINE-INDEPENDENT GLOBAL PROBABILITIES
# ==========================================
# Aggregate ALL valid transitions together across the entire pool
counts = pd.crosstab(df_transitions['recipe_id'], df_transitions['next_recipe_id'])

# Guarantee a square matrix containing all 20 recipes
counts = counts.reindex(index=recipes, columns=recipes, fill_value=0)

# Normalize globally across rows (Row sum = 1.0 probability)
global_matrix = counts.div(counts.sum(axis=1).clip(lower=1), axis=0)


# ==========================================
# STEP 4: BUILD GLOBAL NETWORKX DIRECTED GRAPH
# ==========================================
G = nx.DiGraph()

# Add edges using the global probability pool
for from_recipe in global_matrix.index:
    for to_recipe in global_matrix.columns:
        prob = global_matrix.loc[from_recipe, to_recipe]
        if prob > 0:
            G.add_edge(from_recipe, to_recipe, weight=prob)


# ==========================================
# STEP 5: RUN NETWORK ANALYTICS SUBGROUP DETECTION
# ==========================================
print(f"Total Combined Valid Transitions Processed: {len(df_transitions)}")
print("\n--- DETECTED HARD BOUNDARIES ---")
# Weakly connected components capture structural voids where systems never touch
hard_clusters = list(nx.weakly_connected_components(G))
for i, cluster in enumerate(hard_clusters, 1):
    print(f"Isolated Hard Ecosystem {i}: {sorted(list(cluster))}")

print("\n--- DETECTED SOFT COMMUNITIES ---")
# Louvain finds optimal communities within those hard islands based on probability density
soft_communities = community.louvain_communities(G, weight='weight', seed=42)
for i, comm in enumerate(soft_communities, 1):
    print(f"Soft Production Profile {i}: {sorted(list(comm))}")


# ==========================================
# STEP 6: VISUALIZE LARGE NETWORK RELATIONSHIPS
# ==========================================
plt.figure(figsize=(12, 9))

# Use Kamada-Kawai layout; it spaces independent components out clean and wide
pos = nx.kamada_kawai_layout(G)

# Dynamically color nodes by soft community assignment
community_map = {node: i for i, comm in enumerate(soft_communities) for node in comm}
node_colors = [community_map.get(node, 0) for node in G.nodes()]

# Draw structural recipe nodes
